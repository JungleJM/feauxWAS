def _die(msg):
    sys.stderr.write("ERROR: " + msg + "\n")
    sys.exit(1)


def _manifest_id(text):
    return hashlib.sha256(text.strip().encode("utf-8")).hexdigest()


def load(expect=None):
    """Verify everything in memory; return (manifest, {path: bytes})."""
    got = _manifest_id(MANIFEST_JSON)
    if got != PACK_ID:
        _die("manifest hash %s does not match embedded PACK_ID %s: the bundle "
             "is corrupted" % (got, PACK_ID))
    if expect and expect.strip().lower() != PACK_ID:
        _die("PACK_ID is %s but you expected %s: this is not the bundle you "
             "think it is" % (PACK_ID, expect))
    man = json.loads(MANIFEST_JSON)
    try:
        comp = base64.b64decode("".join(PAYLOAD.split()), validate=True)
    except Exception as e:
        _die("payload is not valid base64 (%s): the bundle is corrupted" % e)
    if hashlib.sha256(comp).hexdigest() != man["payload_sha256"]:
        _die("payload SHA-256 mismatch: the bundle is corrupted")
    blob = zlib.decompress(comp)
    if len(blob) != man["total_bytes"]:
        _die("payload size mismatch: the bundle is corrupted")
    files = {}
    for f in man["files"]:
        data = blob[f["offset"]:f["offset"] + f["size"]]
        if hashlib.sha256(data).hexdigest() != f["sha256"]:
            _die("SHA-256 mismatch for %s" % f["path"])
        files[f["path"]] = data
    return man, files


def _safe_target(dest, rel):
    parts = rel.split("/")
    if rel.startswith("/") or ":" in parts[0] or any(p in ("", "..") for p in parts):
        _die("unsafe path in bundle: %r" % rel)
    root = os.path.abspath(dest)
    target = os.path.abspath(os.path.join(root, *parts))
    if os.path.commonpath([root, target]) != root:
        _die("unsafe path in bundle: %r" % rel)
    return target


def cmd_info(a):
    man, _ = load(a.expect)
    print("PACK_ID     : %s" % PACK_ID)
    print("created     : %s" % man["created"])
    print("note        : %s" % man.get("note", ""))
    print("files       : %d (%d bytes unpacked)" % (len(man["files"]), man["total_bytes"]))
    tops = sorted(set(f["path"].split("/")[0] for f in man["files"]))
    print("top level   : %s" % ", ".join(tops))
    if man.get("excluded"):
        print("excluded    : %d files (%s)" % (len(man["excluded"]),
              ", ".join(sorted(set(os.path.splitext(p)[1] for p in man["excluded"])))))
    print("integrity   : OK")


def cmd_list(a):
    man, _ = load(a.expect)
    for f in man["files"]:
        print("%s  %10d  %s" % (f["sha256"], f["size"], f["path"]))
    print("PACK_ID %s  (%d files, integrity OK)" % (PACK_ID, len(man["files"])))


def cmd_verify(a):
    man, _ = load(a.expect)
    print("OK: all %d files verified. PACK_ID %s" % (len(man["files"]), PACK_ID))


def cmd_unpack(a):
    man, files = load(a.expect)
    dest = a.dest
    targets = [(_safe_target(dest, f["path"]), f) for f in man["files"]]
    clash = [t for t, _ in targets if os.path.exists(t)]
    if clash and not a.force:
        _die("%d files already exist in %s (e.g. %s). Use --force to overwrite "
             "or choose another folder." % (len(clash), os.path.abspath(dest), clash[0]))
    for t, f in targets:
        os.makedirs(os.path.dirname(t), exist_ok=True)
        with open(t, "wb") as fh:
            fh.write(files[f["path"]])
    bad = []
    for t, f in targets:          # re-read from disk and check again
        h = hashlib.sha256()
        with open(t, "rb") as fh:
            h.update(fh.read())
        if h.hexdigest() != f["sha256"]:
            bad.append(t)
    if bad:
        _die("%d files failed verification after writing, e.g. %s" % (len(bad), bad[0]))
    with open(os.path.join(dest, "BUNDLE_MANIFEST.json"), "w", encoding="utf-8") as fh:
        fh.write(MANIFEST_JSON.strip() + "\n")
    print("Unpacked and verified %d files into %s" % (len(targets), os.path.abspath(dest)))
    print("PACK_ID %s" % PACK_ID)


def cmd_check(a):
    man = json.loads(MANIFEST_JSON)
    deps = man.get("check_deps", [])
    print("Python %s" % sys.version.split()[0])
    if not deps:
        print("  (this bundle lists no dependencies to check)")
    missing = []
    for mod in deps:
        try:
            m = importlib.import_module(mod)
            print("  ok       %-24s %s" % (mod, getattr(m, "__version__", "")))
        except Exception as e:
            missing.append(mod)
            print("  MISSING  %-24s (%s)" % (mod, type(e).__name__))
    if missing:
        print("\n%d of %d listed dependencies are missing: %s"
              % (len(missing), len(deps), ", ".join(missing)))
    elif deps:
        print("\nAll %d listed dependencies found." % len(deps))
    paths = [os.path.join(os.path.abspath(a.dest), *p.split("/"))
             for p in man.get("pythonpath", [])]
    if paths:
        print("\nTo use the bundled Python code without installing it, put these on")
        print("PYTHONPATH (separate several with ';' on Windows, ':' on Mac/Linux):")
        for p in paths:
            print("  " + p)
        print("Windows cmd:  set PYTHONPATH=%s" % ";".join(paths))
        print("Mac/Linux:    export PYTHONPATH=%s" % ":".join(paths))


def main():
    ap = argparse.ArgumentParser(description="Self-verifying bundle. PACK_ID " + PACK_ID)
    sub = ap.add_subparsers(dest="cmd")
    for name in ("info", "list", "verify"):
        p = sub.add_parser(name)
        p.add_argument("--expect", help="PACK_ID you expect; abort if different")
    p = sub.add_parser("unpack")
    p.add_argument("dest", nargs="?", default=".", help="destination folder")
    p.add_argument("--expect", help="PACK_ID you expect; abort if different")
    p.add_argument("--force", action="store_true", help="overwrite existing files")
    p = sub.add_parser("check")
    p.add_argument("dest", nargs="?", default=".", help="folder you unpacked into")
    a = ap.parse_args()
    if not a.cmd:
        ap.print_help()
        print("\nPACK_ID %s" % PACK_ID)
        return
    {"info": cmd_info, "list": cmd_list, "verify": cmd_verify,
     "unpack": cmd_unpack, "check": cmd_check}[a.cmd](a)


if __name__ == "__main__":
    main()
